export function homeBlurb(
  slug: string,
  subtitle: string,
  lang: 'vi' | 'en'
): string {
  if (lang !== 'vi') return subtitle;
  return (
    VI[slug] ??
    subtitle
      .replace(/\s*Hỗ trợ nhiều tệp\.?$/, '')
      .replace(' sang định dạng PDF', ' sang PDF')
      .replace(/ của bạn/g, '')
      .replace(/\.$/, '')
  );
}
